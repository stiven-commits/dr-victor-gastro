import pg from 'file:///E:/Dev/Digiorgio/digiorgioapp/node_modules/pg/lib/index.js';
import { writeFile } from 'node:fs/promises';

const { Pool } = pg;
const connectionString = process.env.DATABASE_URL;
const output = process.argv[2] || 'schema.sql';

if (!connectionString) {
  throw new Error('DATABASE_URL is required');
}

const qident = (value) => `"${String(value).replaceAll('"', '""')}"`;
const literal = (value) => `'${String(value).replaceAll("'", "''")}'`;

const pool = new Pool({ connectionString, ssl: false });

const lines = [
  '-- Schema generated from Digiorgio PostgreSQL database.',
  '-- Review before running in production. Prefer running on an empty database or after a backup.',
  '',
  'BEGIN;',
  '',
  'CREATE EXTENSION IF NOT EXISTS pgcrypto;',
  '',
];

try {
  const functions = await pool.query(`
    SELECT p.oid, pg_get_functiondef(p.oid) AS definition
    FROM pg_proc p
    JOIN pg_namespace n ON n.oid = p.pronamespace
    LEFT JOIN pg_depend d ON d.objid = p.oid AND d.deptype = 'e'
    WHERE n.nspname = 'public'
      AND d.objid IS NULL
    ORDER BY p.proname
  `);

  for (const row of functions.rows) {
    lines.push(row.definition.trim() + ';', '');
  }

  const sequences = await pool.query(`
    SELECT sequence_name
    FROM information_schema.sequences
    WHERE sequence_schema = 'public'
    ORDER BY sequence_name
  `);

  for (const row of sequences.rows) {
    lines.push(`CREATE SEQUENCE IF NOT EXISTS ${qident(row.sequence_name)};`);
  }
  if (sequences.rows.length) lines.push('');

  const tables = await pool.query(`
    SELECT c.oid, c.relname AS table_name
    FROM pg_class c
    JOIN pg_namespace n ON n.oid = c.relnamespace
    WHERE n.nspname = 'public'
      AND c.relkind = 'r'
    ORDER BY c.relname
  `);

  for (const table of tables.rows) {
    const columns = await pool.query(`
      SELECT
        a.attname AS column_name,
        pg_catalog.format_type(a.atttypid, a.atttypmod) AS data_type,
        a.attnotnull AS not_null,
        pg_get_expr(ad.adbin, ad.adrelid) AS column_default,
        a.attidentity AS identity
      FROM pg_attribute a
      LEFT JOIN pg_attrdef ad ON ad.adrelid = a.attrelid AND ad.adnum = a.attnum
      WHERE a.attrelid = $1
        AND a.attnum > 0
        AND NOT a.attisdropped
      ORDER BY a.attnum
    `, [table.oid]);

    lines.push(`CREATE TABLE IF NOT EXISTS ${qident(table.table_name)} (`);
    lines.push(columns.rows.map((column) => {
      const parts = [`  ${qident(column.column_name)}`, column.data_type];
      if (column.identity === 'a') parts.push('GENERATED ALWAYS AS IDENTITY');
      if (column.identity === 'd') parts.push('GENERATED BY DEFAULT AS IDENTITY');
      if (column.column_default && !column.identity) parts.push(`DEFAULT ${column.column_default}`);
      if (column.not_null) parts.push('NOT NULL');
      return parts.join(' ');
    }).join(',\n'));
    lines.push(');', '');
  }

  const constraints = await pool.query(`
    SELECT conrelid::regclass::text AS table_name, conname, pg_get_constraintdef(oid) AS definition
    FROM pg_constraint
    WHERE connamespace = 'public'::regnamespace
    ORDER BY CASE contype WHEN 'p' THEN 1 WHEN 'u' THEN 2 WHEN 'c' THEN 3 WHEN 'f' THEN 4 ELSE 5 END, conrelid::regclass::text, conname
  `);

  for (const row of constraints.rows) {
    lines.push(`ALTER TABLE ${row.table_name} DROP CONSTRAINT IF EXISTS ${qident(row.conname)};`);
    lines.push(`ALTER TABLE ${row.table_name} ADD CONSTRAINT ${qident(row.conname)} ${row.definition};`);
  }
  if (constraints.rows.length) lines.push('');

  const indexes = await pool.query(`
    SELECT schemaname, tablename, indexname, indexdef
    FROM pg_indexes
    WHERE schemaname = 'public'
      AND indexname NOT IN (
        SELECT conname
        FROM pg_constraint
        WHERE connamespace = 'public'::regnamespace
      )
    ORDER BY tablename, indexname
  `);

  for (const row of indexes.rows) {
    const indexDef = row.indexdef.replace(/^CREATE INDEX /, 'CREATE INDEX IF NOT EXISTS ');
    lines.push(`${indexDef};`);
  }
  if (indexes.rows.length) lines.push('');

  const views = await pool.query(`
    SELECT table_name, view_definition
    FROM information_schema.views
    WHERE table_schema = 'public'
    ORDER BY table_name
  `);

  for (const row of views.rows) {
    lines.push(`DROP VIEW IF EXISTS ${qident(row.table_name)};`);
    lines.push(`CREATE VIEW ${qident(row.table_name)} AS`);
    lines.push(row.view_definition.trim().replace(/;$/, '') + ';', '');
  }

  const triggers = await pool.query(`
    SELECT tr.tgname, tr.tgrelid::regclass::text AS table_name, pg_get_triggerdef(tr.oid) AS definition
    FROM pg_trigger tr
    JOIN pg_class c ON c.oid = tr.tgrelid
    JOIN pg_namespace n ON n.oid = c.relnamespace
    WHERE NOT tr.tgisinternal
      AND n.nspname = 'public'
    ORDER BY tr.tgrelid::regclass::text, tr.tgname
  `);

  for (const row of triggers.rows) {
    lines.push(`DROP TRIGGER IF EXISTS ${qident(row.tgname)} ON ${row.table_name};`);
    lines.push(`${row.definition};`, '');
  }

  const ownedSequences = await pool.query(`
    SELECT
      seq.relname AS sequence_name,
      tbl.relname AS table_name,
      col.attname AS column_name
    FROM pg_class seq
    JOIN pg_depend dep ON dep.objid = seq.oid
    JOIN pg_class tbl ON tbl.oid = dep.refobjid
    JOIN pg_attribute col ON col.attrelid = tbl.oid AND col.attnum = dep.refobjsubid
    JOIN pg_namespace ns ON ns.oid = seq.relnamespace
    WHERE seq.relkind = 'S'
      AND ns.nspname = 'public'
      AND dep.deptype IN ('a', 'i')
    ORDER BY seq.relname
  `);

  for (const row of ownedSequences.rows) {
    lines.push(`ALTER SEQUENCE ${qident(row.sequence_name)} OWNED BY ${qident(row.table_name)}.${qident(row.column_name)};`);
  }

  lines.push('', 'COMMIT;', '');
  await writeFile(output, lines.join('\n'), 'utf8');
} finally {
  await pool.end();
}
